## Warum Hunde ziehen
Ziehen wird belohnt: Der Hund kommt schneller ans Ziel. Hunde laufen von Natur aus schneller als Menschen.

## Training
1. **Brustgeschirr** statt Halsband, Leine 2–3 m.
2. **Belohnungsposition**: Belohne oft an deinem Bein, wenn die Leine locker ist.
3. **Stehenbleiben** sobald die Leine spannt. Weitergehen, sobald sie locker ist. Alternativ: Richtungswechsel.
4. **Reizarm starten**: Flur, Garten, ruhige Straße. Erst dann belebtere Orte.
5. **Schnüffelpausen** als Belohnung einbauen („Lauf frei“).

## Erfolgskriterium
10 Schritte mit lockerer Leine in ruhiger Umgebung, dann steigern.

## Typischer Fehler
Zu schnell in schwierige Umgebungen wechseln oder inkonsequent mal ziehen lassen.
