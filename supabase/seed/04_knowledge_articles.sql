## Grundprinzip
Verhalten, das sich für den Hund lohnt, wird häufiger. Belohne das, was du sehen willst – sofort (innerhalb von 1–2 Sekunden).

## So gehst du vor
- **Markersignal** aufbauen: ein kurzes Wort („Yes“) oder Klicker, direkt danach Belohnung.
- **Kleine Schritte**: Übung so leicht machen, dass dein Hund zu 80 % Erfolg hat. Erst dann schwieriger.
- **Belohnung passend wählen**: Futter, Spiel, Schnüffeln dürfen, Freigabe zu etwas, das er möchte.
- **Kurze Einheiten**: 3–5 Minuten, lieber öfter am Tag.
- **Unerwünschtes Verhalten managen** statt bestrafen: Situation so gestalten, dass es gar nicht erst passiert, und eine Alternative belohnen.

## Was du vermeidest
Leinenruck, Anschreien, Schreckreize, Stachel- oder Würgehalsband. Sie erzeugen Angst und Stress und verschlechtern oft das Problem.
